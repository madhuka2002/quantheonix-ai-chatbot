class ChatRequest(BaseModel):
    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="The message sent by the user.",
        examples=[
            "Hello, what services does Quantheonix provide?"
        ],
    )

    conversation_id: UUID | None = Field(
        default=None,
        description=(
            "Existing conversation ID. "
            "Send null to begin a new conversation."
        ),
        examples=[
            "f021de92-ffa8-43df-8a08-c7e9e6ab0e5c"
        ],
    )


class ChatResponse(BaseModel):
    conversation_id: UUID = Field(
        description="The ID used to continue this conversation.",
        examples=["f021de92-ffa8-43df-8a08-c7e9e6ab0e5c"],
    )

    reply: str = Field(
        description="The response generated by the AI assistant.",
        examples=[
            "Hello! Quantheonix develops AI, robotics, and XR projects."
        ],
    )


class ResetConversationResponse(BaseModel):
    message: str = Field(
        description="The result of the reset operation.",
        examples=["Conversation reset successfully."],
    )


class ConversationStatsResponse(BaseModel):
    active_conversations: int = Field(
        description="Number of conversations currently stored in memory.",
        examples=[3],
    )

@app.exception_handler(RateLimitExceeded)
async def rate_limit_handler(
    request: Request,
    exception: RateLimitExceeded,
) -> JSONResponse:
    logger.warning(
        "Rate limit exceeded for client %s",
        request.client.host if request.client else "unknown",
    )

    return JSONResponse(
        status_code=429,
        content={
            "detail": (
                "Too many requests. "
                "Please wait before trying again."
            )
        },
    )

