@app.post(
    "/api/chat",
    response_model=ChatResponse,
    tags=["Chat"],
    summary="Send a message to the chatbot",
    description=(
        "Sends a user message to the Quantheonix AI assistant.\n\n"
        "- Send `conversation_id` as `null` to start a new chat.\n"
        "- Reuse the returned `conversation_id` to continue the same chat.\n"
        "- The message must contain between 1 and 2000 characters."
    ),
    response_description=(
        "The generated AI reply and the conversation ID."
    ),
    responses={
        400: {
            "description": "The message is empty after whitespace removal."
        },
        422: {
            "description": "The submitted request failed validation."
        },
        429: {
            "description": "The AI API quota has been reached."
        },
        500: {
            "description": "The chatbot failed to generate a response."
        },
    },
)
@limiter.limit("10/minute")
def chat_endpoint(
    request: Request,
    payload: ChatRequest,
) -> ChatResponse:
    try:
        user_message = payload.message.strip()

        if not user_message:
            raise HTTPException(
                status_code=400,
                detail="Message cannot be empty.",
            )

        conversation_id = payload.conversation_id or uuid4()

        logger.info(
            "Processing chat request for conversation %s",
            conversation_id,
        )

        chat = conversation_manager.get_chat(
            str(conversation_id)
        )

        reply = generate_reply(chat, user_message)

        logger.info(
            "Chat response generated for conversation %s",
            conversation_id,
        )

        return ChatResponse(
            conversation_id=conversation_id,
            reply=reply,
        )

    except HTTPException:
        raise

    except Exception as error:
        error_message = str(error)

        logger.exception(
            "Chat endpoint failed for conversation %s",
            payload.conversation_id,
        )

        if "429" in error_message or "RESOURCE_EXHAUSTED" in error_message:
            raise HTTPException(
                status_code=429,
                detail=(
                    "The chatbot has reached its current API quota. "
                    "Please try again later."
                ),
            ) from error

        raise HTTPException(
            status_code=500,
            detail="The chatbot could not generate a response.",
        ) from error

        raise HTTPException(
            status_code=500,
            detail="The chatbot could not generate a response.",
        ) from error


@app.delete(
    "/api/conversations/{conversation_id}",
    response_model=ResetConversationResponse,
    tags=["Conversations"],
    summary="Reset a conversation",
    description=(
        "Removes the selected conversation from temporary server memory. "
        "Sending another message with the same ID will create a fresh "
        "Gemini chat session."
    ),
    response_description="The result of the conversation reset operation.",
    responses={
        422: {
            "description": "The conversation ID is not a valid UUID."
        },
    },
)
def reset_conversation(
    conversation_id: UUID = Path
    (
        ...,
        description="The UUID of the conversation to reset.",
        examples=["f021de92-ffa8-43df-8a08-c7e9e6ab0e5c"],
    )
) -> ResetConversationResponse:
    was_removed = conversation_manager.remove_chat(
        str(conversation_id)
    )

    if was_removed:
        logger.info(
            "Conversation %s was reset",
            conversation_id,
        )

        return ResetConversationResponse(
            message="Conversation reset successfully.",
        )

    return ResetConversationResponse(
        message="Conversation did not exist or had already expired.",
    )